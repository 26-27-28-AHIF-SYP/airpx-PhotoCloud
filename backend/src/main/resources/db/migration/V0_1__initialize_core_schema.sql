-- Establish the core tables before the incremental V1-V5 migrations run.
-- Existing databases can be baselined at version 0; all statements are safe
-- when some or all of these tables already exist.
DO $$
BEGIN
    IF to_regclass('public.photo') IS NOT NULL AND to_regclass('public.picture') IS NULL THEN
        ALTER TABLE public.photo RENAME TO picture;
    ELSIF to_regclass('public.photo') IS NOT NULL AND to_regclass('public.picture') IS NOT NULL THEN
        RAISE EXCEPTION 'Both public.photo and public.picture exist; merge them before migrating';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(512) NOT NULL
);

CREATE SEQUENCE IF NOT EXISTS album_seq;
CREATE TABLE IF NOT EXISTS album (
    id BIGINT PRIMARY KEY DEFAULT nextval('album_seq'),
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    owner_id BIGINT NOT NULL REFERENCES account(id),
    description VARCHAR(200),
    is_public_on_profile BOOLEAN NOT NULL DEFAULT FALSE,
    qr_code_token VARCHAR(256)
);
ALTER SEQUENCE album_seq OWNED BY album.id;

CREATE TABLE IF NOT EXISTS picture (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES account(id),
    sha256_hash VARCHAR(64) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    captured_at TIMESTAMP WITH TIME ZONE,
    size BIGINT NOT NULL,
    mime_type VARCHAR(255) NOT NULL,
    album_id BIGINT REFERENCES album(id),
    storage_name VARCHAR(255) NOT NULL UNIQUE,
    CONSTRAINT picture_owner_sha256_uq UNIQUE (owner_id, sha256_hash)
);

CREATE TABLE IF NOT EXISTS tag (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_name VARCHAR(50) NOT NULL,
    description VARCHAR(400) NOT NULL
);

CREATE TABLE IF NOT EXISTS picture_tag (
    picture_id BIGINT NOT NULL REFERENCES picture(id) ON DELETE CASCADE,
    tag_id INTEGER NOT NULL REFERENCES tag(id) ON DELETE CASCADE,
    PRIMARY KEY (picture_id, tag_id)
);

CREATE TABLE IF NOT EXISTS account_tag (
    account_id BIGINT NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    tag_id INTEGER NOT NULL REFERENCES tag(id) ON DELETE CASCADE,
    PRIMARY KEY (account_id, tag_id)
);
