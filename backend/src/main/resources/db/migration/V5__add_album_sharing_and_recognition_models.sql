CREATE TABLE IF NOT EXISTS album_permission (
    account_id BIGINT NOT NULL REFERENCES account(id) ON DELETE CASCADE,
    album_id BIGINT NOT NULL REFERENCES album(id) ON DELETE CASCADE,
    can_read BOOLEAN NOT NULL DEFAULT FALSE,
    can_add BOOLEAN NOT NULL DEFAULT FALSE,
    can_delete BOOLEAN NOT NULL DEFAULT FALSE,
    can_rename BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (account_id, album_id)
);

CREATE TABLE IF NOT EXISTS album_share_link (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id BIGINT NOT NULL REFERENCES album(id) ON DELETE CASCADE,
    token VARCHAR(256) NOT NULL UNIQUE,
    password_hash VARCHAR(512),
    expires_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_metadata (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detected_text VARCHAR(200),
    category VARCHAR(100),
    processed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS picture_metadata (
    picture_id BIGINT NOT NULL REFERENCES picture(id) ON DELETE CASCADE,
    ai_metadata_id BIGINT NOT NULL REFERENCES ai_metadata(id) ON DELETE CASCADE,
    PRIMARY KEY (picture_id, ai_metadata_id)
);

CREATE TABLE IF NOT EXISTS face_recognition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_label VARCHAR(300),
    bounding_box VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS picture_face_recognitions (
    face_recognition_id BIGINT NOT NULL REFERENCES face_recognition(id) ON DELETE CASCADE,
    picture_id BIGINT NOT NULL REFERENCES picture(id) ON DELETE CASCADE,
    PRIMARY KEY (face_recognition_id, picture_id)
);
